export function getCatalogRule(item: Pick<CatalogItem, "id" | "category">): BookRuleSection | undefined {
  return itemRules[item.id] ?? categoryRules[item.category];
}

export function splitTraitLabels(traits?: string): string[] {
  if (!traits || traits.trim() === "—") return [];
  return traits
    .split(",")
    .map((trait) => trait.replace(/\*$/, "").trim())
    .filter(Boolean);
}

export function resolveTraitRule(label: string): ResolvedTraitRule | null {
  const match = label.match(/^(.+?)(?:\s*\((.+)\))?$/);
  if (!match) return null;

  const canonicalName = match[1].trim();
  const parameter = match[2]?.trim();
  const baseRule = traitRules[canonicalName];
  if (!baseRule) return null;

  const facts: Array<{ label: string; value: string }> = [];
  if (parameter) {
    const factLabel = canonicalName === "Состояние"
      ? "Состояние X"
      : canonicalName === "Метательное"
        ? "Дальность"
        : canonicalName === "Дальность"
          ? "Новая дальность"
          : "Показатель X";
    facts.push({ label: factLabel, value: parameter });
  }

  const sections = [baseRule];
  if (canonicalName === "Состояние" && parameter && conditionRules[parameter]) {
    sections.push(conditionRules[parameter]);
  }

  return {
    title: label,
    page: baseRule.page,
    facts,
    sections,
  };
}
