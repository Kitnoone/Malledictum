import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// Set PLAYWRIGHT_MODULE to a bundled or locally installed Playwright entry point.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1365, height: 950 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = process.env.APP_URL ?? 'http://127.0.0.1:4173/index.source.html';
mkdirSync('tmp/qa', { recursive: true });
try {
  await page.goto(base);
  await page.locator('.chapter-tabs button').nth(4).click();
  assert.equal(await page.locator('.bestiary-card').count(), 137);
  await page.screenshot({ path: 'tmp/qa/bestiary-desktop.png', fullPage: false });
  await page.getByLabel('Поиск', { exact: true }).fill('амбулл');
  assert.equal(await page.locator('.bestiary-card').count(), 1);
  await page.getByRole('button', { name: /Открыть карточку/ }).click();
  await page.getByRole('heading', { name: 'Амбулл', exact: true, level: 2 }).waitFor();
  assert.equal(await page.locator('.bestiary-characteristics dd').count(), 9);
  await page.getByRole('button', { name: 'Нанести урон', exact: true }).click();
  assert.match(await page.locator('.bestiary-wound-tracker strong').innerText(), /21 \/ 22/);
  await page.locator('.bestiary-detail .supplement-source').click();
  await page.getByRole('heading', { name: 'Амбулл · стр. 143' }).waitFor();
  assert.match(await page.locator('.supplement-pdf-dialog header small').innerText(), /справочник противников/);
  await page.getByRole('button', { name: 'Закрыть источник' }).click();
  await page.getByRole('button', { name: 'Закрыть карточку' }).click();
  await page.getByRole('button', { name: 'В избранное: Амбулл', exact: true }).click();
  await page.reload();
  await page.locator('.chapter-tabs button').nth(4).click();
  await page.getByRole('button', { name: '☆ Избранное', exact: true }).click();
  assert.equal(await page.locator('.bestiary-card').count(), 1);
  await page.locator('.chapter-tabs button').nth(2).click();
  await page.locator('.catalog-source-filter select').selectOption('mechanicus');
  await page.getByRole('searchbox', { name: 'Поиск предметов' }).fill('Дуговая винтовка');
  assert.equal(await page.locator('.catalog-list-row').count(), 2);
  const row = page.locator('.catalog-list-row').filter({ has: page.getByText('Дуговая винтовка', { exact: true }) });
  await row.getByRole('button', { name: 'Добавить Дуговая винтовка', exact: true }).click();
  assert.equal(await page.locator('.manifest-row').count(), 1);
  await row.locator('.catalog-list-copy').click();
  await page.getByRole('heading', { name: 'Дуговая винтовка', exact: true, level: 2 }).waitFor();
  await page.locator('.weapon-screen-header .supplement-source').click();
  await page.getByRole('heading', { name: 'Дуговая винтовка · стр. 80' }).waitFor();
  await page.getByRole('button', { name: 'Закрыть источник' }).click();
  await page.getByRole('button', { name: 'Вернуться к листу' }).click();
  await page.reload();
  await page.locator('.chapter-tabs button').nth(2).click();
  assert.equal(await page.locator('.manifest-row').count(), 1);
  await page.locator('.chapter-tabs button').nth(1).click();
  await page.getByRole('button', { name: 'Таланты', exact: true }).click();
  await page.locator('.catalog-source-filter select').selectOption('mechanicus');
  assert.equal(await page.locator('.talent-catalog-row').count(), 24);
  await page.getByRole('button', { name: /Талант Архитектурный ум/ }).click();
  await page.getByRole('heading', { name: 'Архитектурный ум', exact: true, level: 2 }).waitFor();
  assert.match(await page.locator('.rule-detail-dialog .source-badge').first().innerText(), /механикус/i);
  await page.getByRole('button', { name: 'Закрыть окно' }).click();
  await page.locator('.chapter-tabs button').nth(3).click();
  await page.getByRole('button', { name: 'Механикус', exact: true }).click();
  await page.getByRole('button', { name: '+1 заряд' }).click();
  assert.match(await page.locator('.bestiary-wound-tracker strong').innerText(), /1 \/ 3/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.chapter-tabs button').nth(4).click();
  await page.screenshot({ path: 'tmp/qa/bestiary-mobile.png', fullPage: false });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows horizontally');
  await page.locator('.bestiary-card-open').first().click();
  await page.screenshot({ path: 'tmp/qa/bestiary-card-mobile.png', fullPage: false });
  assert.ok(await page.evaluate(() => document.querySelector('.bestiary-detail').scrollWidth <= innerWidth), 'Card overflows horizontally');
  assert.deepEqual(errors, [], 'Uncaught browser errors');
  console.log('PASS: desktop/mobile bestiary, source routing, favorites, inventory persistence, Mechanicus talents and Motive Force.');
} catch (error) {
  console.log('Browser errors:', errors);
  console.log((await page.locator('body').innerText()).slice(0, 4500));
  await page.screenshot({ path: 'tmp/qa/failure.png', fullPage: false });
  throw error;
} finally { await browser.close(); }
